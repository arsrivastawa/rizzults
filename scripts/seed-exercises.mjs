// Transforms the raw free-exercise-db JSON (https://github.com/yuhonas/free-exercise-db)
// into seed rows for the SQLite `exercises` table, mapping each exercise to a tracking_type.
//
// Run from the repo root:  node scripts/seed-exercises.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const inputPath = join(__dirname, 'free-exercise-db', 'exercises.json');
const outputPath = join(__dirname, '..', 'src', 'db', 'exercises.seed.ts');

const capFirst = (s) => s.charAt(0).toUpperCase() + s.slice(1);
const capWords = (s) => s.split(' ').map(capFirst).join(' ');

// Timed isometric holds — the dataset marks these as bodyweight strength, but
// they are logged by duration, not reps.
const TIMED_HOLDS = new Set(['plank', 'side bridge', 'wall sit', 'l-sit']);

function trackingType(e) {
  const name = e.name.toLowerCase();
  const category = (e.category || '').toLowerCase();
  const equipment = (e.equipment || '').toLowerCase();

  if (TIMED_HOLDS.has(name)) {
    return 'time';
  }
  if (category === 'stretching') {
    return 'time';
  }
  if (category === 'cardio') {
    if (/rope|jump rope|skipping/.test(name)) {
      return 'count';
    }
    if (/(bicycl|bike|cycle|jog|run|walk|row|skat|stair|step|elliptical|recumbent|sprint)/.test(name)) {
      return 'distance_time';
    }
    return 'time';
  }
  if (category === 'strongman' && /(carry|farmer|yoke|walk)/.test(name)) {
    return 'weight_time';
  }
  if (!equipment || equipment === 'body only' || equipment === 'bodyweight') {
    return 'bodyweight_reps';
  }
  return 'weight_reps';
}

const raw = JSON.parse(readFileSync(inputPath, 'utf8'));

const seen = new Set();
const rows = [];
for (const e of raw) {
  if (!e.id || seen.has(e.id)) {
    continue;
  }
  seen.add(e.id);
  rows.push({
    id: e.id,
    name: e.name,
    category: e.category || null,
    equipment: e.equipment ? capFirst(e.equipment) : null,
    primaryMuscles: (e.primaryMuscles || []).map(capWords).join(', '),
    secondaryMuscles: (e.secondaryMuscles || []).map(capWords).join(', '),
    mechanic: e.mechanic || null,
    force: e.force || null,
    instructions: (e.instructions || []).join('\n'),
    trackingType: trackingType(e),
  });
}

const counts = rows.reduce((acc, r) => {
  acc[r.trackingType] = (acc[r.trackingType] || 0) + 1;
  return acc;
}, {});

const header =
  '// Generated by scripts/seed-exercises.mjs — do not edit by hand.\n' +
  '// Source: https://github.com/yuhonas/free-exercise-db (public domain / Unlicense)\n\n' +
  'export type SeedExercise = {\n' +
  '  id: string;\n' +
  '  name: string;\n' +
  '  category: string | null;\n' +
  '  equipment: string | null;\n' +
  '  primaryMuscles: string;\n' +
  '  secondaryMuscles: string;\n' +
  '  mechanic: string | null;\n' +
  '  force: string | null;\n' +
  '  instructions: string;\n' +
  '  trackingType: string;\n' +
  '};\n\n';

const body = `export const exerciseSeeds: SeedExercise[] = ${JSON.stringify(rows)};\n`;

writeFileSync(outputPath, header + body, 'utf8');

console.log(`Wrote ${rows.length} exercise seed rows to ${outputPath}`);
console.log('tracking_type distribution:', counts);
